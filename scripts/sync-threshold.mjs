// Copies the Threshold test sites, byte for byte, into src/threshold-sites.js.
//
//   node scripts/sync-threshold.mjs <path to a Threshold checkout>
//
// Nothing is edited: page HTML and manifest.json are embedded exactly as they are
// in Threshold, together with the commit they came from, so any field run can be
// tied to the exact version of the sites it was served.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join } from "node:path";

const repo = process.argv[2];
if (!repo) {
  console.error("usage: node scripts/sync-threshold.mjs <path to Threshold checkout>");
  process.exit(1);
}
const siteRoot = join(repo, "test-site", "sites");
const manifest = JSON.parse(readFileSync(join(repo, "test-site", "manifest.json"), "utf8"));
const commit = execFileSync("git", ["-C", repo, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();

const pages = {};
for (const site of manifest.sites) {
  for (const file of readdirSync(join(siteRoot, site)).sort()) {
    if (file.endsWith(".html")) pages[`${site}/${file}`] = readFileSync(join(siteRoot, site, file), "utf8");
  }
}

const out = `// GENERATED by scripts/sync-threshold.mjs. Do not edit by hand.
// Source: github.com/Resonantly-Feral/threshold, commit ${commit}
export const THRESHOLD_COMMIT = ${JSON.stringify(commit)};
export const THRESHOLD_MANIFEST = ${JSON.stringify(manifest, null, 2)};
export const THRESHOLD_PAGES = ${JSON.stringify(pages, null, 2)};
`;
writeFileSync(new URL("../src/threshold-sites.js", import.meta.url), out);
console.log(`Embedded ${Object.keys(pages).length} pages from ${manifest.sites.length} sites at ${commit.slice(0, 7)}.`);
